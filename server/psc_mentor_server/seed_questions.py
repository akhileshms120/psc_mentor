def seed_questions(db: Database) -> None:
    seeded = db.one("SELECT COUNT(*) AS n FROM questions WHERE verification = 'seed'")["n"]
    if seeded >= len(SEED):
        return  # already there; saves ~90 round trips to a hosted database on every start
    for topic, stem, options, answer, explanation in SEED:
        add_question(db, type="original_mock", topic_id=topic, stem=stem, options=options,
                     answer_index=answer, explanation=explanation, verification="seed")
